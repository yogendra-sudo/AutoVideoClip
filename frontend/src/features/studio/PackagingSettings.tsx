import { Switch } from 'antd'
import { t } from '../../i18n'
import { Row, Segmented } from '../../ui'
import { packagingLabel, packagingFallbackHint } from './packagingLabel'
import type { Draft, Packaging } from './types'
import { effectiveSubtitles } from './subtitleState'

const TITLE_MAX = { zh: 12, en: 36 }
const STYLES: Record<Packaging['template'], { value: NonNullable<Packaging['style']>; label: string }[]> = {
  interview_zh: [{ value: 'classic', label: 'Classic' }, { value: 'boxed', label: 'Caption bar' }, { value: 'spotlight', label: 'Spotlight' }],
  podcast_en: [{ value: 'pop', label: 'Word pop' }, { value: 'boxed', label: 'Caption bar' }, { value: 'cinematic', label: 'Cinematic' }],
}

/**
 * Editing for automatic template packaging. This release only allows the two title lines and
 * the editor tags switch; captions, nameplates and tags themselves come from the template.
 */
export default function PackagingSettings({ draft, patch }: { draft: Draft; patch: (changes: Partial<Draft>) => void }) {
  const packaging = draft.packaging
  if (!packaging) return null
  const fallbackHint = packagingFallbackHint(packaging, [], effectiveSubtitles(draft))
  const max = TITLE_MAX[packaging.audience_language]
  const lines = [packaging.title_lines[0] ?? '', packaging.title_lines[1] ?? '']
  const update = (changes: Partial<Packaging>) => patch({ packaging: { ...packaging, ...changes } })
  const setLine = (index: number, value: string) => {
    const next = [...lines]
    next[index] = value.slice(0, max)
    // Lines stay in place while typing (saving drops empty ones); only an empty second line is dropped.
    update({ title_lines: next[1].trim() ? next : [next[0]] })
  }
  return <>
    <Row stack label={t('Template')} hint={t('Captions, name tags and layout are generated by the template for the platform you chose.')}>
      <span className="studio-muted">{packagingLabel(packaging)}{fallbackHint ? ` · ${fallbackHint}` : ''}</span>
    </Row>
    <Row stack label={t('Style')} hint={t('Changes the look and motion of captions; layout and colours stay the same.')}>
      <Segmented size="sm" ariaLabel={t('Style')} value={packaging.style ?? STYLES[packaging.template][0].value}
        options={STYLES[packaging.template].map(option => ({ value: option.value, label: t(option.label) }))}
        onChange={value => update({ style: value as Packaging['style'] })} />
    </Row>
    <Row stack label={t('Title')} hint={packaging.template === 'interview_zh' ? t('Shown at the top for the whole video; the second line uses the accent colour.') : t('Shown for about 3 seconds at the start.')}>
      {lines.map((line, index) => <input key={index} className="ac-input" aria-label={t('Title line {{n}}', { n: index + 1 })} maxLength={max}
        value={line} placeholder={index === 0 ? t('First line') : t('Second line (optional)')} onChange={e => setLine(index, e.target.value)} />)}
    </Row>
    <Row label={t('Subtitles')} hint={t('Off: no captions burned in; title and nameplates stay.')}>
      <Switch size="small" checked={packaging.captions_enabled !== false} onChange={checked => update({ captions_enabled: checked })} aria-label={t('Subtitles')} />
    </Row>
    {packaging.template === 'interview_zh' && <Row label={t('Editor tags')} hint={t('Short editor comments that pop in on key lines.')}>
      <Switch size="small" checked={packaging.tags_enabled} disabled={!packaging.tags.length} onChange={checked => update({ tags_enabled: checked })} aria-label={t('Editor tags')} />
    </Row>}
  </>
}
